def q(sheet):
    """表名加引号（表名以 _ 开头或含特殊字符时必须）"""
    return f"'{sheet}'"


def rng(sheet, col, r0, r1):
    return f"{q(sheet)}!${col}${r0}:${col}${r1}"


def cell(sheet, ref):
    c = ''.join(ch for ch in ref if ch.isalpha())
    r = ''.join(ch for ch in ref if ch.isdigit())
    return f"{q(sheet)}!${c}${r}"


