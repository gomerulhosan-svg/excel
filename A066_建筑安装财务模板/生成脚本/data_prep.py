def _wb1():
    return openpyxl.load_workbook(F1, data_only=False)


def journal():
    """流水登记 221 笔原样：(日期, 账户, 摘要, 收入, 支出)。
       原表把收款记成「负数支出」（收到股东借款 −10000），这里按原样带过去，模板里自动当收入算（校验列会提醒）"""
    ws = _wb1()['流水登记']
    out = []
    for r in range(10, ws.max_row + 1):
        d, acc, memo, inc, exp = (ws.cell(r, c).value for c in range(1, 6))
        if d is None and acc is None and memo is None:
            continue
        inc = inc if isinstance(inc, (int, float)) and inc != 0 else None
        exp = exp if isinstance(exp, (int, float)) and exp != 0 else None
        out.append((d, acc, str(memo).replace('\n', ' ') if memo else None, inc, exp))
    return out


def april_attendance():
    """工资表月分表（26 年 4 月）：每人各项目天数、本月发、代扣个税、已退回"""
    ws = _wb1()['工资表月分表']
    heads = {c: ws.cell(2, c).value for c in range(7, 12)}
    out = []
    for r in range(3, 35):
        n = ws.cell(r, 2).value
        if not n:
            continue
        days = {PAY_COL[heads[c]]: ws.cell(r, c).value for c in heads if isinstance(ws.cell(r, c).value, (int, float))}
        u = ws.cell(r, 21).value          # 合计天数：管理人员填 1（按月）
        out.append(dict(name=n, days=days, month_units=u if isinstance(u, (int, float)) and not days else None,
                        paid=ws.cell(r, 38).value, tax=ws.cell(r, 40).value, refund=ws.cell(r, 42).value))
    return out


def person_history():
    """三个人的个人往来（建账前的历史）→ 算期初：个人借给公司的（公司欠他）"""
    wb = openpyxl.load_workbook(F1, data_only=True)
    res = {}
    for sh, who in (('老板个人往来', '王伟'), ('老板2个人明细', '聂辉')):
        ws = wb[sh]
        lent = 0
        for r in range(3, ws.max_row + 1):
            v = ws.cell(r, 4).value
            if isinstance(v, (int, float)):
                lent += v
        res[who] = round(lent, 2)
    return res


