def inref(sh, col, last=REF_END):
    """录入表 / 基础资料某列的锚定区域（从表头行开始），配合 INDEX(区域, n+1) 用"""
    h = {SH_CASH: CASH_HDR, SH_WL: WL_HDR, SH_BASE: BASE_HDR, SH_UNIT: UNIT_HDR}[sh]
    return f"{sh}!${col}${h}:${col}${last}"


def esc(x):
    """当 SUMIFS/COUNTIFS 的条件用时，把名字里的 ~ * ? 转义成普通字符"""
    return f'SUBSTITUTE(SUBSTITUTE(SUBSTITUTE({x},"~","~~"),"*","~*"),"?","~?")'


def dr(name, lo, hi):
    """日期条件片段：name,">="&lo,name,"<="&hi"""
    return f'{name},">="&{lo},{name},"<="&{hi}'


def seg_crit(name, sel):
    """板块条件：选择格空＝全部（用一个永远不会出现的值做「不等于」）"""
    return f'{name},IF({sel}="","<>@@全部@@",{esc(sel)})'
