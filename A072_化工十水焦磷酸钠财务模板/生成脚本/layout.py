def inref(sh, col, last=REF_END, block=None, hdr=None):
    """录入表 / 基础资料 / 物料档案某列的锚定区域（从表头行开始），配合 INDEX(区域, n+1) 用"""
    if hdr is None:
        if sh == SH_BASE:
            hdr = BASE_HDR[block]
        elif sh == SH_ITEM:
            hdr = ITEM_PRD_HDR if block == '产品' else ITEM_RM_HDR
        else:
            hdr = HDR
    return f"{sh}!${col}${hdr}:${col}${last}"


def esc(x):
    """当 SUMIFS/COUNTIFS/MATCH 的条件用时，把 ~ * ? 转义成普通字符"""
    return f'SUBSTITUTE(SUBSTITUTE(SUBSTITUTE({x},"~","~~"),"*","~*"),"?","~?")'


def norm(x):
    """名字、单号规范写法：去半角/全角/不换行空格，半角括号改全角"""
    return (f'SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(TRIM({x}&"")," ",""),"　","")," ",""),'
            f'"(","（"),")","）")')


def mon(d):
    """日期 → 账套年度里的月（1～12；不在本年度或早于建账日＝0）"""
    return f'IF(AND({d}>=P_建账日,{d}<=P_年末),MONTH({d}),0)'


def dr(name, lo, hi):
    return f'{name},">="&{lo},{name},"<="&{hi}'


def any_crit(name, sel):
    """选择格空＝全部"""
    return f'{name},IF({sel}="","<>@@全部@@",{esc(sel)})'


def mk(no, m):
    """数字键：号×100＋月"""
    return f'({no})*100+({m})'
