"""A072 化工 · 隐藏表 _资（资金台帐逐条：取数、记账口径、本金事件、摊销、往来、即时余额块表、校验）。
   第 n 条在第 n+1 行，取数 INDEX(资金台帐!$X$4:$X$1048576, n+1)，插行删行排序不错位。列见 layout.ZI_COLS，块表 layout.ZI_BLK。
   「原始」列（到「有效」R 为止，含私有列 DP 特、DR 所属年月）只看本行和基础资料，不引用 P_截止、引擎、往来余额。
   私有列（别的模块不要引用）：DP 特（这一行用的那一边的特殊记号 0～9）、DQ 账户日期键（现金/票据账户的有效行：账户号×SORT_M＋日期）、
   DR 所属年月（所属月份格解析成 年×100＋月；空＝-1，看不懂＝0）。
   跟 layout 说明不一样的两处（汇报里写了）：费用月——跨月=2（所属月早于建账）的行＝0（建账前的费用，不进本年费用池、费用统计）；
   月摊额、摊尾差带符号（按费用额：支出＋、收入－，退回的预付款冲减摊销）。"""
from layout import *
from common import F_HELP, DATE, MONEY
from s_mirror import _hdr, _lab, _ix, chain, vdate, txt, raw, numv, badnum, unit_match, ym_ok, TXT_DATE

M = SORT_M
_P0 = CI(ZI_BLK['前大']) + N_ACC + 1                       # 块表后空一列
ZI_PRIV = dict(特=CL(_P0), 账户日期键=CL(_P0 + 1), 所属年月=CL(_P0 + 2))
FEE1 = ('4101', '5401', '5601', '5602', '5603')            # 「费用类」一级（跨月、所属月份、分摊 1123 只对它们生效）
VAT1 = FEE1 + ('5711', '1601', '1801')                      # 可抵进项的对方一级


def _fee(ab, codes=FEE1):
    return f'AND({ab}>0,OR(' + ','.join(f'{ab}={kh(k)}' for k in codes) + '))'


def _ym_own(x):
    """所属月份格 → 年×100＋月：1～12（数字或文字「9」「9月」）＝账套年度；2026-09 / 2026年9月 / 202609 / 真日期都认；空＝-1；看不懂＝0"""
    t = f'SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE({txt(x)},"年","-"),"月",""),"/","-"),".","-")'
    tv = (f'IFERROR(IF(ISNUMBER(FIND("-",{t})),VALUE(LEFT({t},4))*100+VALUE(SUBSTITUTE(MID({t},6,2),"-","")),'
          f'IF(VALUE({t})<=12,P_年度*100+VALUE({t}),VALUE({t}))),0)')
    num = (f'IF(AND({x}>=1,{x}<=12,INT({x})={x}),P_年度*100+{x},IF(AND({x}>=200001,{x}<=209912),{x},'
           f'IF(AND({x}>=36526,{x}<73051),YEAR({x})*100+MONTH({x}),0)))')
    return f'IF({txt(x)}="",-1,IF(ISNUMBER({x}),{num},{tv}))'


def build_zi(ws):
    _hdr(ws, ZI_COLS)
    for k, col in ZI_PRIV.items():
        _lab(ws, f'{col}1', k)
    Z, C = ZI, CASH_COLS
    lastc = lambda c0: CL(CI(c0) + N_ACC - 1)
    pre_rng = f'${ZI_BLK["前"]}$2:${lastc(ZI_BLK["前"])}${N_BLK + 1}'
    pmx_rng = f'${ZI_BLK["前大"]}$2:${lastc(ZI_BLK["前大"])}${N_BLK + 1}'
    dbp = 'IFERROR(MATCH("待补票",票种_名称,0),0)'
    for i in range(N_CASH):
        r, n = i + 2, i + 1
        b = i // BLK + 1
        bs = 2 + (b - 1) * BLK
        ws[f'A{r}'] = n
        x = lambda k: _ix(SH_CASH, C[k], f'$A{r}')
        c = lambda k: f'{Z[k]}{r}'
        p = lambda k: f'{ZI_PRIV[k]}{r}'
        s = lambda col: f'${col}${bs}:{col}{r}'
        B, Cn, D, E, F, G, H = c('日期'), c('账户号'), c('账户类型'), c('类别号'), c('归类'), c('单位'), c('单位号')
        I, J, K, L, Mn, Nn, O = c('收入'), c('支出'), c('金额坏'), c('编号键'), c('报销人号'), c('报销项目号'), c('票种号')
        Pm, Q, R_, S = c('月'), c('所属月'), c('有效'), c('净额')
        AA, AB, AC, AE = c('原对方号'), c('原对方一级'), c('跨月'), c('分摊')
        sp, key, ym = p('特'), p('账户日期键'), p('所属年月')
        at, ct, ut = txt(x('账户')), txt(x('收支类别')), txt(x('往来单位'))
        # ── 原始 ──
        ws[B] = f'={vdate(x("日期"))}'
        ws[Cn] = f'=IF({at}="",0,IFERROR(MATCH({esc(at)},账户_名称,0),0))'
        ws[D] = f'=IF({Cn}=0,0,INDEX(账户_类型号,{Cn}))'
        ws[E] = f'=IF({ct}="",0,IFERROR(MATCH({esc(ct)},类别_名称,0),0))'
        ws[F] = f'=IF({E}=0,"",INDEX(类别_归类,{E})&"")'
        u0 = f'IF({ut}="",IF({E}>0,INDEX(类别_默认往来,{E})&"",""),{norm(x("往来单位"))})'
        ws[G] = f'={unit_match(u0, "简称", u0)}'
        ws[H] = f'=IF({G}="",0,IFERROR(MATCH({esc(G)},位_简称,0),0))'
        ws[I] = f'={numv(x("收入"))}'
        ws[J] = f'={numv(x("支出"))}'
        ws[K] = f'=IF(OR({badnum(x("收入"))},{badnum(x("支出"))}),1,0)'
        nb = norm(x('编号'))
        ws[L] = f'=IF({nb}="","","#"&{nb})'
        t = txt(x('报销人'))
        ws[Mn] = f'=IF({t}="",0,IFERROR(MATCH({esc(t)},人员_姓名,0),0))'
        t = txt(x('报销项目'))
        ws[Nn] = f'=IF({t}="",0,IFERROR(MATCH({esc(t)},报销_名称,0),0))'
        ws[sp] = f'=IF({E}=0,0,IF({I}<>0,INDEX(类别_收特,{E}),INDEX(类别_付特,{E})))'
        tk = txt(x('票种'))
        ws[O] = (f'=IF({tk}<>"",IFERROR(MATCH({esc(tk)},票种_名称,0),0),IF(OR({D}=5,{D}=6),{dbp},'
                 f'IF(AND({sp}=5,{Nn}>0),INDEX(报销_票种号,MAX(1,{Nn})),IF({E}>0,INDEX(类别_票种号,MAX(1,{E})),0))))')
        ws[Pm] = f'={mon(B)}'
        ws[ym] = f'={_ym_own(x("所属月份"))}'
        ws[Q] = (f'=IF({ym}=-1,0,IF(NOT({ym_ok(ym)}),99,IF({ym}<P_年度*100+P_建账月,-1,'
                 f'IF(INT({ym}/100)>P_年度,99,MOD({ym},100)))))')
        ws[R_] = (f'=IF(AND({B}>0,{B}>=P_建账日,{B}<=P_年末,{Cn}>0,{D}>0,{E}>0,{K}=0,({I}<>0)+({J}<>0)=1,{sp}<>9),1,0)')
        # ── 往下可以引用截止日、别的隐藏表 ──
        ws[S] = f'=IF({R_}=1,ROUND({I}-{J},2),0)'
        ws[c('余额')] = (f'=IF(OR({R_}<>1,{D}<1,{D}>4),"",ROUND(INDEX(账户_期初,{Cn})+INDEX({pre_rng},{b},{Cn})'
                       f'+SUMIFS({s(Z["净额"])},{s(Z["账户号"])},{Cn}),2))')
        ws[key] = f'=IF(AND({R_}=1,{D}>=1,{D}<=4),{Cn}*{M}+{B},"")'
        kk = s(ZI_PRIV['账户日期键'])
        ws[c('日期乱')] = (f'=IF({key}="",0,IF(OR({B}<INDEX({pmx_rng},{b},{Cn}),'
                         f'COUNTIFS({kk},">"&{key},{kk},"<"&({Cn}+1)*{M})>0),1,0))')
        ws[c('录入行')] = f'=ROW({SH_CASH}!$A${HDR})+$A{r}'
        has = 'OR(' + ','.join(raw(x(k)) for k in ('日期', '账户', '收支类别', '往来单位', '摘要', '收入', '支出', '编号',
                                                    '报销人', '报销项目', '票种', '所属月份')) + ')'
        ws[c('末行')] = f'=IF({has},{c("录入行")},0)'
        ws[c('排序键')] = f'=IF({R_}=1,{B}*{M}+$A{r},"")'
        # ── 记账 ──
        h1 = f'MAX(1,{H})'
        utp = f'IF({H}>0,INDEX(位_类型,{h1})&"","")'
        wl = (f'IF(OR({utp}="客户",AND({utp}="客户和供应商",{I}<>0)),{kh("1122")},'
              f'IF(OR({utp}="供应商",{utp}="物流",{utp}="客户和供应商"),{kh("2202")},IF({I}<>0,{kh("224199")},{kh("122199")})))')
        jk = f'IF(IF({H}>0,INDEX(位_出借人类别,{h1}),0)=1,{kh("2001")},{kh("224102")})'
        lx = f'IF(IF({H}>0,INDEX(位_借款利率,{h1}),0)>0,{kh("2231")},{kh("560301")})'
        fh = f'IF(IF({H}>0,INDEX(位_投资利率,{h1}),0)>0,{kh("2232")},{kh("310401")})'
        bx = f'IF({Nn}>0,INDEX(报销_科目号,{Nn}),0)'
        base = f'IF({I}<>0,INDEX(类别_收号,{E}),INDEX(类别_付号,{E}))'
        e1 = f'MAX(1,{E})'
        tc = (f'IF(AND({base}>0,INDEX(科目_一级号,MAX(1,{base}))={kh("1801")},{B}>=DATE(P_年度,P_投产月,1),'
              f'INDEX(类别_投产后号,{e1})>0),INDEX(类别_投产后号,{e1}),{base})')
        ws[AA] = (f'=IF({E}=0,0,CHOOSE({sp}+1,{tc},{wl},{jk},{lx},{fh},{bx},{kh("224101")},{kh("122103")},'
                  f'{kh("3001")},0))')
        ws[AB] = f'=IF({AA}>0,INDEX(科目_一级号,{AA}),0)'
        fee = _fee(AB)
        ws[AE] = (f'=IF({R_}<>1,0,IF(AND({AB}>0,{AB}={kh("1801")}),1,IF(AND(INDEX(类别_分摊月数,{e1})>1,{fee}),2,0)))')
        ws[AC] = (f'=IF(OR({R_}<>1,{AE}>0,NOT({fee})),0,IF({Q}=-1,2,IF(AND({Q}>0,{Q}<>99,{Q}<>{Pm}),1,0)))')
        ws[c('费用月')] = f'=IF({R_}<>1,0,IF({AC}=1,{Q},IF({AC}=2,0,{Pm})))'
        ws[c('对方号')] = (f'=IF({R_}<>1,0,IF({AE}=2,{kh("1123")},IF({AC}=1,{kh("224103")},IF({AC}=2,{kh("224199")},'
                         f'IF({AA}=0,{kh("224199")},{AA})))))')
        noded = f'OR({sp}<>5,{Nn}=0,INDEX(报销_不抵,MAX(1,{Nn}))=0)'
        ws[c('可抵率')] = (f'=IF({R_}<>1,0,IF(AND(P_纳税人=1,OR({_fee(AB, VAT1)},{AE}=2),INDEX(类别_不抵,{e1})=0,{noded},'
                         f'{O}>0),INDEX(票种_税率,MAX(1,{O})),0))')
        ws[c('税额')] = f'=ROUND(ABS({S})/(1+{c("可抵率")})*{c("可抵率")},2)'
        ws[c('不含税')] = f'=ROUND(ABS({S})-{c("税额")},2)'
        ws[c('账户科目号')] = f'=IF({Cn}=0,0,INDEX(账户_科目号,{Cn}))'
        ws[c('现金')] = f'=IF(AND({D}>=1,{D}<=3),1,0)'
        ws[c('现流号')] = (f'=IF(OR({R_}<>1,{c("现金")}=0),0,IF(AND({sp}=5,{Nn}>0),INDEX(报销_现流,MAX(1,{Nn})),'
                         f'IF({I}<>0,INDEX(类别_现流收,{e1}),INDEX(类别_现流付,{e1}))))')
        ws[c('现流额')] = f'=IF({c("现流号")}>0,{S},0)'
        # ── 本金事件 ──
        AN = c('出借人号')
        ws[AN] = (f'=IF({R_}<>1,0,IF({D}=5,IF(OR({sp}=3,{sp}=4),0,INDEX(账户_出借人号,{Cn})),'
                  f'IF(OR({sp}=2,{sp}=6,{sp}=8),IF({H}>0,INDEX(位_出借人号,{h1}),0),0)))')
        ws[c('性质')] = f'=IF({AN}=0,0,IF(AND({D}<>5,{sp}=8),2,1))'
        ws[c('本金变动')] = f'=IF({AN}=0,0,IF({D}=5,-{S},{S}))'
        ws[c('息键')] = f'=IF({AN}=0,0,{AN}*1000+{c("性质")}*100+{Pm})'
        ws[c('本金乘日')] = f'={c("本金变动")}*{B}'
        # ── 摊销 ──
        nm_ = f'IF(INDEX(类别_分摊月数,{e1})>0,INDEX(类别_分摊月数,{e1}),P_摊销月数)'
        ws[c('摊目标号')] = (f'=IF({AE}=1,IF(INDEX(类别_摊进,{e1})=2,{kh("560207")},{kh("410106")}),IF({AE}=2,{AA},0))')
        ws[c('摊始月')] = f'=IF({AE}=1,MAX(P_投产月,{Pm}),IF({AE}=2,IF(AND({Q}>0,{Q}<>99),{Q},{Pm}),0))'
        ws[c('摊止月')] = f'=IF({AE}=0,0,{c("摊始月")}+{nm_}-1)'
        ws[c('月摊额')] = f'=IF({AE}=0,0,ROUND({c("费用额")}/{nm_},2))'
        ws[c('摊尾差')] = f'=IF({AE}=0,0,ROUND({c("费用额")}-{c("月摊额")}*{nm_},2))'
        # ── 往来、显示 ──
        is1122 = f'AND({AB}>0,{AB}={kh("1122")})'
        is2202 = f'AND({AB}>0,{AB}={kh("2202")})'
        ws[c('应收变动')] = f'=IF({is1122},-{S},0)'
        ws[c('应付变动')] = f'=IF({is2202},{S},0)'
        ws[c('回款键')] = f'=IF(AND({R_}=1,{is1122},{I}>0,{H}>0),{H}*{M}+{B},"")'
        ws[c('付款键')] = f'=IF(AND({R_}=1,{is2202},{J}>0,{H}>0),{H}*{M}+{B},"")'
        ws[c('关联固定行')] = f'=IF({L}="",0,IFERROR(MATCH({esc(L)},固_编号键,0),0))'
        pre = 'TEXT(YEAR(P_截止)*100+MONTH(P_截止),"000000")'
        ws[c('本月垫付号')] = (f'=IF(LEFT({L},9)="#"&{pre}&"-X",MAX(0,INT(IFERROR(VALUE(MID({L},10,9)),0))),0)')
        ws[c('待补票')] = f'=IF(AND({R_}=1,{O}>0,{O}={dbp}),1,0)'
        zy = txt(x('摘要'))
        ws[c('显示摘要')] = f'=IF({zy}="",{ct},{zy})'
        ws[c('费用额')] = f'=IF({R_}<>1,0,IF({S}<0,1,-1)*{c("不含税")})'
        # ── 校验：✗ 一条链、⚠/ℹ 一条链 ──
        Y = c('末行')
        acct_t, cat_t = f'{at}', f'{ct}'
        sm = _ix(SH_BASE, CAT_COLS['说明'], E, '类别')
        aa_in = lambda *codes: 'OR(' + ','.join(f'{AA}={kh(k)}' for k in codes) + ')'
        lender = f'OR({H}=0,INDEX(位_出借人号,{h1})=0)'
        ws[c('错')] = '=' + chain([
            (f'{Y}=0', '""'),
            (f'{B}=0', 'IF(' + raw(x('日期')) + ',IF(ISTEXT(' + x('日期') + '),' + TXT_DATE
             + ',"✗ 日期看不懂（输 8-15 或 2026/8/15，不要用 8.15）"),"✗ 没填日期（同一天的也要填）")'),
            (f'YEAR({B})<>P_年度', '"✗ 日期不是 "&P_年度&" 年的：一本账只记一年，下一年的请开新一本（上一年的记在上一本）"'),
            (f'{B}<P_建账日', '"✗ 日期早于建账日 "&TEXT(P_建账日,"yyyy-mm-dd")&"：建账前的钱已经算在期初余额里了，这一行删掉"'),
            (f'{K}=1', '"✗ 金额不是数字（10000+200 要写成 =10000+200，或者分两行记）"'),
            (f'AND({I}=0,{J}=0)', '"✗ 没填金额"'),
            (f'AND({I}<>0,{J}<>0)', '"✗ 收入、支出只能填一个（分两行记）"'),
            (f'{Cn}=0', f'IF({acct_t}="","✗ 没选账户","✗ 账户「"&{acct_t}&"」不在【基础资料】②账户里")'),
            (f'{D}=0', '"✗ 账户「"&' + acct_t + '&"」在【基础资料】②里的类型不对（选现金、银行、微信支付宝、票据、垫付、备用金）"'),
            (f'{E}=0', f'IF({cat_t}="","✗ 没选收支类别","✗ 收支类别「"&{cat_t}&"」不在【基础资料】③收支类别里")'),
            (f'{sp}=9', '"✗ 「"&' + cat_t + '&"」不能选"&IF(TRIM(' + sm + '&"")="","（停用了）","："&TRIM(' + sm + '&""))'),
            (f'AND(OR({D}=5,{D}=6),{aa_in("122104", "122105")})',
             f'IF({D}=5,"✗ 老板垫付账户不能选「"&{cat_t}&"」：老板个人付的钱类别选真实用途（伙食费、员工报销…），公司还老板选「垫付现金已报」只在银行记一行",'
             f'"✗ 备用金账户不能选「"&{cat_t}&"」：发、退备用金在银行（现金）账户记「发备用金」，往来单位选拿钱的人")'),
            (f'AND({D}=4,{aa_in("122104")})', '"✗ 内部转账两边都要是现金、银行、微信支付宝账户：承兑到期、贴现选「承兑到期/贴现入账」"'),
            (f'AND({D}=5,{sp}=6)', '"✗ 老板垫付账户不用记还款：公司还老板的钱只在银行（现金）账户记一行，类别「垫付现金已报」，往来单位选老板"'),
            (f'AND({D}=6,{sp}=7)', '"✗ 备用金账户不用记「发备用金」：发、退备用金在银行（现金）账户记，往来单位选拿钱的人"'),
            (f'AND({sp}=5,{Mn}=0)', 'IF(' + raw(x('报销人')) + ',"✗ 报销人「"&' + txt(x('报销人'))
             + '&"」不在【基础资料】⑤人员里","✗ 员工报销要填报销人")'),
            (f'AND({sp}=5,{Nn}=0)', 'IF(' + raw(x('报销项目')) + ',"✗ 报销项目「"&' + txt(x('报销项目'))
             + '&"」不在【基础资料】④报销项目里","✗ 员工报销要选报销项目（科目、票种、现金流量按它算）")'),
            (f'AND({tk}<>"",{O}=0)', '"✗ 票种「"&' + tk + '&"」不在【基础资料】⑥票种里"'),
            (f'{AA}=0', f'IF({sp}=5,"✗ 报销项目「"&{txt(x("报销项目"))}&"」没配会计科目（或科目编码不在【会计科目】里）：先记到 其他应付款-其他",'
             f'"✗ 收支类别「"&{cat_t}&"」没配会计科目（或科目编码不在【会计科目】里）：先记到 其他应付款-其他")'),
            (f'AND(OR({is1122},{is2202}),{H}=0)',
             f'IF({G}="","✗ 收付货款要选往来单位（"&IF({is1122},"客户","供应商、物流单位")&"）",'
             f'"✗ 「"&{G}&"」不在【往来单位】里：新单位先去加一行（别人代付的，往来单位填欠款那家，代付人写摘要）")'),
            (f'AND({is1122},INDEX(位_是客户,{h1})=0)', '"✗ 「"&' + G + '&"」在【往来单位】里不是客户（两边都有往来的，类型改成「客户和供应商」）"'),
            (f'AND({is2202},INDEX(位_是供应商,{h1})=0)',
             '"✗ 「"&' + G + '&"」在【往来单位】里不是供应商、物流（两边都有往来的，类型改成「客户和供应商」）"'),
            (f'AND(OR({sp}=2,{sp}=6,{sp}=8),{lender})',
             f'IF({G}="","✗ 「"&{cat_t}&"」要选往来单位（出借人：老板、合伙人、银行…）",'
             f'"✗ 「"&{G}&"」不是出借人：「"&{cat_t}&"」的往来单位要选【往来单位】里类型是出借人的")'),
            (f'AND({Q}=99,{fee})', '"✗ 所属月份看不懂或不在 "&P_年度&" 年（填 9 或 2026-9 都行）"'),
        ])
