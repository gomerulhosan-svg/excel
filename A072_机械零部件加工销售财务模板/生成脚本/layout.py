def inref(sh, col, last=REF_END, block=None):
    """录入表 / 基础资料某列的锚定区域（从表头行开始），配合 INDEX(区域, n+1) 用；基础资料要给 block"""
    h = BASE_HDR[block] if sh == SH_BASE else HDR
    return f"{sh}!${col}${h}:${col}${last}"


def esc(x):
    """当 SUMIFS/COUNTIFS/MATCH 的条件用时，把名字里的 ~ * ? 转义成普通字符"""
    return f'SUBSTITUTE(SUBSTITUTE(SUBSTITUTE({x},"~","~~"),"*","~*"),"?","~?")'


def norm(x):
    """名字、单号规范写法：去半角/全角/不换行空格，半角括号改全角"""
    return (f'SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(TRIM({x}&"")," ",""),"　","")," ",""),'
            f'"(","（"),")","）")')


def ym(d):
    return f'IF({d}>0,YEAR({d})*100+MONTH({d}),0)'


def dr(name, lo, hi):
    return f'{name},">="&{lo},{name},"<="&{hi}'


def any_crit(name, sel):
    """选择格空＝全部"""
    return f'{name},IF({sel}="","<>@@全部@@",{esc(sel)})'


