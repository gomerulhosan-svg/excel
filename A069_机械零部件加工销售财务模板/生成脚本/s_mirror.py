def _goods_common(ws, r, x, c, C, unit_key, is_sale):
    ws[c('日期')] = f'={vdate(x("日期"))}'
    ws[c(unit_key)] = f'={txt(x("客户" if is_sale else "供应商"))}'
    un = norm(c(unit_key))
    ws[c('单位号')] = f'={unit_no(un)}'
    ws[c('单位')] = f'=IF({c("单位号")}>0,INDEX(位_简称,{c("单位号")}),{un})'
    ws[c('数量')] = f'={numv(x("数量"))}'
    ws[c('计量单位')] = f'={txt(x("计量单位"))}'
    ws[c('单价')] = f'={numv(x("单价"))}'
    ws[c('金额')] = f'=IF(ISNUMBER({x("金额")}),ROUND({x("金额")},2),ROUND({c("数量")}*{c("单价")},2))'
    ws[c('待定价')] = f'=IF(AND(NOT({raw(x("金额"))}),NOT({raw(x("单价"))}),{c("数量")}<>0),1,0)'
    ws[c('备注')] = f'={txt(x("备注"))}'
    ws[c('年月')] = f'={ym(c("日期"))}'


def _goods_check(c, x, unit_key, is_sale):
    who = '客户' if is_sale else '供应商'
    flag = '是客户' if is_sale else '是供应商'
    u = c('单位号')
    has = (f'OR({raw(x("日期"))},{c(unit_key)}<>"",{raw(x("数量"))},{raw(x("单价"))},{raw(x("金额"))},'
           f'{txt(x("产品" if is_sale else "物料"))}<>"")')
    rows = [
        (f'NOT({has})', '""'),
        (f'{c("日期")}=0', 'IF(' + raw(x('日期')) + ',IF(ISTEXT(' + x('日期') + '),' + TXT_DATE + ',"✗ 日期看不懂（输 10-8 或 2026/10/8，不要用 10.8）"),"✗ 没填日期")'),
        (f'{c(unit_key)}=""', f'"✗ 没填{who}"'),
        (f'{u}=0', '"✗ 「"&' + c(unit_key) + '&"」不在【往来单位】里，先去加一行"'),
        (f'INDEX(位_{flag},MAX(1,{u}))=0', '"✗ 「"&' + c('单位') + f'&"」在往来单位里不是{who}（两边都有往来的，类型改成「客户和供应商」）"'),
        (f'{c("日期")}<P_建账日', ('"✗ 日期早于建账日：建账前的货已经在期初欠款里了；建账前发货、现在才定价的，日期改成建账日、备注写原日期"'
                                if is_sale else '"✗ 日期早于建账日：建账前的货已经在期初欠款里了；建账前到货、现在才定价的，日期改成建账日、备注写原日期"')),
        (f'OR({badnum(x("数量"))},{badnum(x("单价"))},{badnum(x("金额"))})', '"✗ 数量、单价、金额要填数字"'),
        (f'AND({c("数量")}=0,{c("金额")}=0,{c("待定价")}=0)', '"✗ 没填数量、金额"'),
        (f'{c("待定价")}=1', '"⚠ 还没定价：定了价回到这一行补单价（日期不要改）"'),
        (f'AND(ISNUMBER({x("金额")}),{c("数量")}*{c("单价")}<>0,ABS({c("金额")}-{c("数量")}*{c("单价")})>0.5)',
         '"⚠ 金额跟数量×单价对不上（按填的金额算）"'),
        (f'{c("日期")}>P_截止', '"⚠ 日期晚于截止日期 "&TEXT(P_截止,"yyyy-mm-dd")&"，暂不算"'),
        (f'ABS(YEAR({c("日期")})-YEAR(P_截止))>1', '"⚠ 日期的年份对吗？"'),
    ]
    return has, rows


def build_xs(ws):
    _hdr(ws, XS_COLS)
    Z, C = XS, SALE_COLS
    for i in range(N_SALE):
        r, n = i + 2, i + 1
        ws[f'A{r}'] = n
        x = lambda k: _ix(SH_SALE, C[k], f'$A{r}')
        c = lambda k: f'{Z[k]}{r}'
        _goods_common(ws, r, x, c, C, '客户原文', True)
