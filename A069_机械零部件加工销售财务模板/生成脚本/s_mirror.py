def build_piao(ws):
    _hdr(ws, PIAO_COLS)
    Z, C = PIAO, INV_COLS
    for i in range(N_INV):
        r, n = i + 2, i + 1
        ws[f'A{r}'] = n
        x = lambda k: _ix(SH_INV, C[k], f'$A{r}')
        c = lambda k: f'{Z[k]}{r}'
        ws[c('日期')] = f'={vdate(x("日期"))}'
        ws[c('单位原文')] = f'={txt(x("往来单位"))}'
        un = norm(c('单位原文'))
        ws[c('单位号')] = f'={unit_no(un)}'
        ws[c('单位')] = f'=IF({c("单位号")}>0,INDEX(位_简称,{c("单位号")}),{un})'
        u = c('单位号')
        isc = f'INDEX(位_是客户,MAX(1,{u}))'
        iss = f'INDEX(位_是供应商,MAX(1,{u}))'
        d = txt(x('方向'))
        ws[c('方向')] = (f'=IF(OR({d}="开出",{d}="收到"),{d},IF({u}=0,"",IF(AND({isc}=1,{iss}=0),"开出",'
                       f'IF(AND({iss}=1,{isc}=0),"收到",""))))')
        ws[c('发票号码')] = f'={txt(x("发票号码"))}'
        ws[c('号码键')] = f'=IF({c("发票号码")}="","","#"&{norm(c("发票号码"))})'
        ws[c('发票类型')] = f'={txt(x("发票类型"))}'
        t = x('税率')
        tt = txt(t)
        ws[c('税率')] = (f'=IF({tt}="",0.13,IF(ISNUMBER({t}),IF({t}>=1,{t}/100,{t}),IF({tt}="免税",0,'
                       f'IFERROR(VALUE(SUBSTITUTE(SUBSTITUTE({tt},"%",""),"％",""))/100,-1))))')
        ws[c('价税合计')] = f'={numv(x("价税合计"))}'
        ws[c('税额')] = (f'=IF(ISNUMBER({x("税额")}),ROUND({x("税额")},2),IF({c("税率")}>=0,'
                       f'ROUND({c("价税合计")}/(1+{c("税率")})*{c("税率")},2),0))')
        ws[c('不含税')] = f'=ROUND({c("价税合计")}-{c("税额")},2)'
        ws[c('对应单号')] = f'={txt(x("对应单号"))}'
        ws[c('备注')] = f'={txt(x("备注"))}'
        ws[c('有效')] = f'=IF(AND({c("日期")}>0,{c("单位原文")}<>"",{c("价税合计")}<>0),1,0)'
        ws[c('计入往来')] = f'=IF(AND({c("有效")}=1,{c("日期")}>=P_建账日,{u}>0,{c("方向")}<>""),1,0)'
        ws[c('年月')] = f'={ym(c("日期"))}'
        has = (f'OR({raw(x("日期"))},{c("单位原文")}<>"",{c("发票号码")}<>"",{raw(x("价税合计"))})')
        fh = x('发票号码')
        calc = f'ROUND({c("价税合计")}/(1+{c("税率")})*{c("税率")},2)'
        ws[c('校验')] = '=' + chain([
            (f'NOT({has})', '""'),
            (f'{c("日期")}=0', 'IF(' + raw(x('日期')) + ',IF(ISTEXT(' + x('日期') + '),' + TXT_DATE + ',"✗ 日期看不懂（输 10-8 或 2026/10/8，不要用 10.8）"),"✗ 没填开票日期")'),
            (f'{c("单位原文")}=""', '"✗ 没填往来单位"'),
            (f'{u}=0', '"✗ 「"&' + c('单位原文') + '&"」不在【往来单位】里，先去加一行"'),
            (f'{c("方向")}=""', '"✗ 这家既是客户又是供应商：要选开出还是收到"'),
            (f'{badnum(x("价税合计"))}', '"✗ 价税合计要填数字"'),
            (f'{c("价税合计")}=0', '"✗ 没填价税合计"'),
            (f'{c("税率")}<0', '"✗ 税率看不懂（选 13%、9%、6%、3%、1%、0%）"'),
            (f'{c("日期")}<P_建账日', '"✗ 日期早于建账日：建账前的票已经算在期初未开票、欠票里了，这一行删掉"'),
            (f'AND({c("号码键")}<>"",COUNTIFS(票_号码键,{esc(c("号码键"))},票_单位号,{u})>1)', '"✗ 发票号码重复了"'),
            (f'AND(ISNUMBER({fh}),{fh}>99999999)', '"⚠ 发票号码被当成数字了（会变样）：把这一格设成文本再重输"'),
            (f'AND({c("方向")}="开出",{isc}=0)', '"⚠ 开出给供应商？方向是不是填反了"'),
            (f'AND({c("方向")}="收到",{iss}=0)', '"⚠ 从客户那收到发票？方向是不是填反了"'),
            (f'AND(ISNUMBER({x("税额")}),ABS({c("税额")}-{calc})>1)', '"⚠ 税额跟价税合计、税率算出来的差 1 元以上"'),
            (f'{c("日期")}>P_截止', '"⚠ 日期晚于截止日期 "&TEXT(P_截止,"yyyy-mm-dd")&"，暂不算"'),
            (f'{c("价税合计")}<0', '"ℹ 负数：红字发票"'),
        ])
        ws[c('录入行')] = f'=ROW({SH_INV}!$A${HDR})+$A{r}'
        ws[c('末行')] = f'=IF({has},{c("录入行")},0)'
        ws[c('排序键')] = f'=IF({c("计入往来")}=1,{c("日期")}*{M}+$A{r},"")'


