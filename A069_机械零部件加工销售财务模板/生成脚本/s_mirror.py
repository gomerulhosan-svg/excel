    pre_rng = f'${ZI_BLK["前"]}$2:${CL(CI(ZI_BLK["前"]) + N_ACC - 1)}${N_BLK + 1}'
    pmx_rng = f'${ZI_BLK["前大"]}$2:${CL(CI(ZI_BLK["前大"]) + N_ACC - 1)}${N_BLK + 1}'
    for i in range(N_CASH):
        r, n = i + 2, i + 1
        b = i // BLK + 1
        bs = 2 + (b - 1) * BLK
        ws[f'A{r}'] = n
        x = lambda k: _ix(SH_CASH, C[k], f'$A{r}')
        c = lambda k: f'{Z[k]}{r}'
        s = lambda k: f'${Z[k]}${bs}:{Z[k]}{r}'
        # 原始取数（到「有效」为止不准引用 P_截止、P_建账日）
        ws[c('日期')] = f'={vdate(x("日期"))}'
        ws[c('账户')] = f'={txt(x("账户"))}'
        ws[c('账户号')] = f'=IF({c("账户")}="",0,IFERROR(MATCH({esc(c("账户"))},账户_名称,0),0))'
        ws[c('类别')] = f'={txt(x("类别"))}'
        ws[c('归类')] = f'=IF({c("类别")}="","",IFERROR(INDEX(类别_归类,MATCH({esc(c("类别"))},类别_名称,0)),""))'
        ws[c('往来原文')] = f'={txt(x("往来单位"))}'
        un = norm(c('往来原文'))
        ws[c('单位号')] = f'={unit_no(un)}'
        ws[c('单位')] = f'=IF({c("单位号")}>0,INDEX(位_简称,{c("单位号")}),{un})'
