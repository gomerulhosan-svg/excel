def build_wei(ws):
    _hdr(ws, WEI_COLS)
    W, C = WEI, UNIT_COLS
    upto = lambda nm: f'{nm},"<="&P_截止'
    for i in range(N_UNIT):
        r, n = i + 2, i + 1
        ws[f'A{r}'] = n
        x = lambda k: _ix(SH_UNIT, C[k], f'$A{r}')
        c = lambda k: f'{W[k]}{r}'
        ws[c('简称')] = f'={norm(x("简称"))}'
        for k in ('类型', '全称', '别名', '联系人', '电话', '地址', '默认采购类别', '备注'):
            ws[c(k)] = f'={txt(x(k))}'
        for k in ('期初应收', '期初应付', '期初未开票', '期初欠票'):
            ws[c(k)] = f'=N({x(k)})'
        ws[c('要开票')] = f'=IF({txt(x("开票"))}="不要",0,1)'
        ws[c('全称规')] = f'=IF({c("全称")}="","",{norm(c("全称"))})'
        al = f'SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE({c("别名")},"，","、"),",","、"),"；","、"),";","、"),"/","、")'
        ws[c('别名规')] = f'=IF({c("别名")}="","","、"&{norm(al)}&"、")'
        ws[c('有效')] = f'=IF({c("简称")}<>"",1,0)'
        ws[c('是客户')] = f'=IF(AND({c("有效")}=1,OR({c("类型")}="客户",{c("类型")}="客户和供应商")),1,0)'
        ws[c('是供应商')] = f'=IF(AND({c("有效")}=1,OR({c("类型")}="供应商",{c("类型")}="客户和供应商")),1,0)'
        v1 = f'{c("有效")}<>1'
        ws[c('发货')] = f'=IF({v1},0,ROUND(SUMIFS(销_金额,销_单位号,$A{r},销_计入往来,1,{upto("销_日期")}),2))'
        ws[c('回款')] = f'=IF({v1},0,ROUND(SUMIFS(资_净额,资_单位号,$A{r},资_归类,"收客户货款",{upto("资_日期")}),2))'
        ws[c('到货')] = f'=IF({v1},0,ROUND(SUMIFS(采_金额,采_单位号,$A{r},采_计入往来,1,{upto("采_日期")}),2))'
        ws[c('付款')] = f'=IF({v1},0,ROUND(SUMIFS(资_支出额,资_单位号,$A{r},资_归类,"付供应商货款",{upto("资_日期")}),2))'
        ws[c('已开票')] = (f'=IF({v1},0,ROUND(SUMIFS(票_价税合计,票_单位号,$A{r},票_方向,"开出",票_计入往来,1,'
                         f'{upto("票_日期")}),2))')
        ws[c('应开票')] = (f'=IF({v1},0,ROUND({c("期初未开票")}+SUMIFS(销_金额,销_单位号,$A{r},销_计入往来,1,销_开票,1,'
                         f'{upto("销_日期")}),2))')
        ws[c('未开票')] = f'=ROUND({c("应开票")}-{c("已开票")},2)'
        ws[c('已收票')] = (f'=IF({v1},0,ROUND(SUMIFS(票_价税合计,票_单位号,$A{r},票_方向,"收到",票_计入往来,1,'
                         f'{upto("票_日期")}),2))')
        ws[c('应收票')] = (f'=IF({v1},0,ROUND({c("期初欠票")}+SUMIFS(采_金额,采_单位号,$A{r},采_计入往来,1,采_开票,1,'
                         f'{upto("采_日期")}),2))')
        ws[c('欠票')] = f'=ROUND({c("应收票")}-{c("已收票")},2)'
        for k, nm in (('最后发货', '销_发货键'), ('最后回款', '资_回款键'), ('最后到货', '采_到货键'), ('最后付款', '资_付款键')):
            ws[c(k)] = (f'=IF({v1},0,MAX(0,IFERROR(LARGE({nm},COUNTIF({nm},">="&($A{r}+1)*{M})+1)-$A{r}*{M},0)))')
        fs = f'IFERROR(SMALL(销_发货键,COUNTIF(销_发货键,"<"&$A{r}*{M})+1)-$A{r}*{M},0)'
        ws[c('首次发货')] = f'=IF({v1},0,IF({fs}>={M},0,{fs}))'
        ws[c('待定价发货')] = f'=IF({v1},0,COUNTIFS(销_单位号,$A{r},销_待定价,1,销_计入往来,1,{upto("销_日期")}))'
        ws[c('待定价到货')] = f'=IF({v1},0,COUNTIFS(采_单位号,$A{r},采_待定价,1,采_计入往来,1,{upto("采_日期")}))'
        ws[c('待审批')] = f'=IF({v1},0,SUMIFS(批_申请金额,批_单位号,$A{r},批_状态码,0))'
        ws[c('已批未付')] = f'=IF({v1},0,SUMIFS(批_未付,批_单位号,$A{r}))'
        start = f'IF({c("期初应收")}>0.005,P_建账日,{c("首次发货")})'
        ws[c('没回款天数')] = f'=IF(AND({c("有效")}=1,{c("应收")}>0.005),P_截止-MAX({c("最后回款")},{start}),"")'
        has = (f'OR({c("简称")}<>"",{c("类型")}<>"",{c("全称")}<>"",{c("期初应收")}<>0,{c("期初应付")}<>0,'
               f'{c("期初未开票")}<>0,{c("期初欠票")}<>0)')
        nm, ty = c('简称'), c('类型')
        ws[c('校验')] = '=' + chain([
            (f'NOT({has})', '""'),
            (f'{nm}=""', '"✗ 没填简称（这一行不算）"'),
            (f'COUNTIF(位_简称,{esc(nm)})>1', '"✗ 简称重复了"'),
            (f'NOT({in_list(UNIT_TYPES, ty)})', '"✗ 类型要选：客户、供应商、客户和供应商、其他"'),
            (f'AND({c("全称规")}<>"",{c("全称规")}<>{nm},COUNTIF(位_简称,{esc(c("全称规"))})>0)', '"✗ 全称跟别家的简称一样"'),
            (f'AND({c("全称规")}<>"",COUNTIF(位_全称规,{esc(c("全称规"))})>1)', '"✗ 全称跟别家重复了"'),
            (f'NOT({in_list(UNIT_INV + [""], txt(x("开票")))})', '"✗ 开票只能填「要」或「不要」（空＝要）"'),
            (f'COUNTIF(位_别名规,"*、"&{esc(nm)}&"、*")>0', '"⚠ 别家的别名里也有这个简称"'),
            (f'AND({c("默认采购类别")}<>"",NOT({in_list(PUR_TYPES, c("默认采购类别"))}))', '"⚠ 默认采购类别不在清单里（按原材料算）"'),
            (f'AND({c("是客户")}=0,{c("期初应收")}<>0)', '"⚠ 不是客户，填的期初应收不算"'),
            (f'AND({c("是供应商")}=0,{c("期初应付")}<>0)', '"⚠ 不是供应商，填的期初应付不算"'),
            (f'AND({c("是供应商")}=1,{c("应付")}<-0.005)',
             '"⚠ 预付 "&TEXT(-' + c('应付') + ',"#,##0.00")&"：是先付的款，还是到了货没记采购登记？"'),
            (f'AND({c("是客户")}=1,{c("应收")}<-0.005)', '"ℹ 预收 "&TEXT(-' + c('应收') + ',"#,##0.00")'),
        ])
        ws[c('录入行')] = f'=ROW({SH_UNIT}!$A${HDR})+$A{r}'
        ws[c('末行')] = f'=IF({has},{c("录入行")},0)'
        # 期初应收应付只对相应类型算
        ws[c('应收')] = f'=IF({c("是客户")}=1,ROUND({c("期初应收")}+{c("发货")}-{c("回款")},2),ROUND({c("发货")}-{c("回款")},2))'
        ws[c('应付')] = f'=IF({c("是供应商")}=1,ROUND({c("期初应付")}+{c("到货")}-{c("付款")},2),ROUND({c("到货")}-{c("付款")},2))'


# ───────────────────────── _固：固定支出 ─────────────────────────
def build_gu(ws):
    _hdr(ws, GU_COLS)
    G, C = GU, FIX_COLS
    for i in range(N_FIX):
        r, n = i + 2, i + 1
        ws[f'A{r}'] = n
        x = lambda k: _ix(SH_FIX, C[k], f'$A{r}')
        c = lambda k: f'{G[k]}{r}'
        ws[c('编号')] = f'={txt(x("编号"))}'
        ws[c('编号键')] = f'=IF({c("编号")}="","","#"&{norm(c("编号"))})'
        ws[c('项目')] = f'={txt(x("项目"))}'
        ws[c('类别')] = f'={txt(x("类别"))}'
        un = norm(x('收款单位'))
        u = unit_no(un)
        ws[c('收款单位')] = f'=IF({u}>0,INDEX(位_简称,{u}),{un})'
