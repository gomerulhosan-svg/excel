def build_par(ws):
    P = lambda k: f'{SH_BASE}!$C${PAR_ROW[k]}'
    b = lambda k: PAR[k]
    first = 'IF(COUNTIF(资_日期,">0")=0,DATE(2026,1,1),SMALL(资_日期,COUNTIF(资_日期,0)+1))'
    home = f'{SH_HOME}!${HOME_END[0]}${HOME_END[1:]}'
    rows = {
        '公司名称': f'=TRIM({P("公司名称")}&"")',
        '建账日': f'=IF(ISNUMBER({P("建账日")}),INT({P("建账日")}),{first})',
        '回款天数': f'=IF(N({P("回款天数")})>0,N({P("回款天数")}),60)',
        '期初库存': f'=IF(ISNUMBER({P("期初库存")}),{P("期初库存")},"")',
        '月折旧': f'=N({P("月折旧")})',
        '日期上限': f'={b("建账日")}+800',
        '挡后日期': '=MAX($E$2:$E$4)',
        '近月笔数': '=SUM($F$2:$F$4)',
        '截止被挡': f'=IF(AND({b("挡后日期")}>0,{b("近月笔数")}<=2),1,0)',
        '最后日期': f'=MAX({b("建账日")},IF({b("截止被挡")}=1,{b("挡后日期")},MAX($D$2:$D$4)))',
        '截止': f'=IF(ISNUMBER({home}),INT({home}),{b("最后日期")})',
        '年度': f'=YEAR({b("截止")})',
        '截止年月': f'=YEAR({b("截止")})*100+MONTH({b("截止")})',
        '月初': f'=DATE(YEAR({b("截止")}),MONTH({b("截止")}),1)',
        '年初': f'=DATE(YEAR({b("截止")}),1,1)',
        '资金末行': f'=MAX(MAX(资_末行),{HDR + 1})+1',
        '销售末行': f'=MAX(MAX(销_末行),{HDR + 1})+1',
        '采购末行': f'=MAX(MAX(采_末行),{HDR + 1})+1',
        '发票末行': f'=MAX(MAX(票_末行),{HDR + 1})+1',
        '审批末行': f'=MAX(MAX(批_末行),{HDR + 1})+1',
        '计划末行': f'=MAX(MAX(购_末行),{HDR + 1})+1',
        '往来末行': f'=MAX(MAX(位_末行),{HDR + 1})+1',
        '固定末行': f'=MAX(MAX(固_末行),{HDR + 1})+1',
    }
    yymm = f'TEXT(MOD(YEAR({b("截止")}),100)*100+MONTH({b("截止")}),"0000")'
    rows['下一审批号'] = f'="SP"&{yymm}&"-"&TEXT(COUNTIF(批_单号,"SP"&{yymm}&"-*")+1,"000")'
    # D：资金、销售、采购三张表里不超过上限的最晚日期；E：比 L（D 的最大）早 32 天以上的最晚日期；F：L 前 31 天内（含 L）的笔数
    for i, nm in enumerate(('资_日期', '销_日期', '采_日期')):
        ws[f'C{2 + i}'] = nm
        ws[f'D{2 + i}'] = f'=IFERROR(LARGE({nm},COUNTIF({nm},">"&{b("日期上限")})+1),0)'
        ws[f'E{2 + i}'] = f'=IFERROR(LARGE({nm},COUNTIF({nm},">"&(MAX($D$2:$D$4)-32))+1),0)'
        ws[f'F{2 + i}'] = f'=COUNTIFS({nm},">"&(MAX($D$2:$D$4)-31),{nm},"<="&MAX($D$2:$D$4))'
    for i, (key, _t, _tr, hr, cap) in enumerate(BASE_BLOCKS):
        if i + 1 < len(BASE_BLOCKS):
            nxt = BASE_BLOCKS[i + 1][1]
            rows[f'{key}位'] = f'=IFERROR(MATCH("{nxt}",{SH_BASE}!$A:$A,0)-ROW({SH_BASE}!$A${hr})-1,{cap})'
        else:
            rows[f'{key}位'] = f'={cap + 300}'
    ws['A1'] = '全书共用的参数（自动，别改）'
    for k, cell in PAR.items():
        r = int(cell[1:])
        ws[f'A{r}'] = k
        ws[cell] = rows[k]


