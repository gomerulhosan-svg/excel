def _blk_counter(ws, cnt, n, cond_range, crit, src_first=2):
    """计数列（50 行一段）：第 i 条＝前 i 条里满足 COUNTIF(区域, crit) 的个数"""
    for i in range(n):
        r = i + 2
        bs = 2 + (i // BLK) * BLK
        base = f'{cnt}{bs - 1}+' if bs > 2 else ''
        ws[f'{cnt}{r}'] = f'={base}COUNTIF({cond_range(bs, r)},{crit})'


def build_list(ws):
    ws['A1'] = '账户'
    ws['F1'] = '收支类别'
    ws['I1'] = '人员'
    ws['K1'] = '库存估值'
    for i in range(LIST_N):
        r, n = i + 2, i + 1
        if n <= N_ACC:
            g = lambda k: _ix(SH_BASE, ACC_COLS[k], n, '账户')
            a = f'{LIST_ACC["名称"]}{r}'
            ws[a] = f'=IF({n}>P_账户位,"",TRIM({g("名称")}&""))'
            ws[f'{LIST_ACC["类型"]}{r}'] = f'=IF({a}="","",IF(TRIM({g("类型")}&"")="","银行",TRIM({g("类型")}&"")))'
            ws[f'{LIST_ACC["期初余额"]}{r}'] = f'=IF({a}="",0,N({g("期初余额")}))'
            ws[f'{LIST_ACC["可用"]}{r}'] = f'=IF({a}="",0,IF({LIST_ACC["类型"]}{r}="票据",0,1))'
        if n <= N_CAT:
            g = lambda k: _ix(SH_BASE, CAT_COLS[k], n, '类别')
            a = f'{LIST_CAT["名称"]}{r}'
            ws[a] = f'=IF({n}>P_类别位,"",TRIM({g("名称")}&""))'
            ws[f'{LIST_CAT["归类"]}{r}'] = f'=IF({a}="","",TRIM({g("归类")}&""))'
        if n <= N_PER:
            g = lambda k: _ix(SH_BASE, PER_COLS[k], n, '人员')
            ws[f'{LIST_PER["姓名"]}{r}'] = f'=IF({n}>P_人员位,"",TRIM({g("姓名")}&""))'
        if n <= N_STK:
            g = lambda k: _ix(SH_BASE, STK_COLS[k], n, '库存')
            k_ = f'{LIST_STK["年月"]}{r}'
            ws[k_] = f'=IF({n}>P_库存位,0,{month_any(g("月份"))})'
            ws[f'{LIST_STK["估值"]}{r}'] = f'=IF({k_}=0,0,N({g("估值")}))'
            ws[f'{LIST_STK["有值"]}{r}'] = f'=IF(AND({k_}>0,ISNUMBER({g("估值")})),1,0)'
            ws[f'{LIST_STK["键"]}{r}'] = f'=IF({LIST_STK["有值"]}{r}=1,{k_},"")'
    # 压紧的清单（下拉用）
    for key, (out, src, cap) in COMPACT.items():
        cnt = COMPACT_CNT[key]
        for i in range(cap):
            r = i + 2
            prev = f'+{cnt}{r - 1}' if i else ''
            ws[f'{cnt}{r}'] = f'=IF({src}{r}<>"",1,0){prev}'
            ws[f'{out}{r}'] = (f'=IF({i + 1}>${out}$1,"",INDEX(${src}$2:${src}${cap + 1},'
                               f'MATCH({i + 1},${cnt}$2:${cnt}${cap + 1},0)))')
        ws[f'{out}1'] = f'={cnt}{cap + 1}'
    # 往来单位下拉：全部 / 客户 / 供应商（来源 _位）
    for key, flag in (('往来单位', '有效'), ('客户', '是客户'), ('供应商', '是供应商')):
        out, cnt, fc = UNIT_DV[key], COMPACT_CNT[key], WEI[flag]
        _blk_counter(ws, cnt, N_UNIT, lambda bs, r: f'{H_WEI}!${fc}${bs}:${fc}{r}', 1)
        for i in range(N_UNIT):
            r = i + 2
            ws[f'{out}{r}'] = (f'=IF({i + 1}>${out}$1,"",INDEX(位_简称,MATCH({i + 1},${cnt}$2:${cnt}${N_UNIT + 1},0)))')
        ws[f'{out}1'] = f'={cnt}{N_UNIT + 1}'
    # 关联单号下拉：待付款的审批单（单号＋收款单位）＋ 固定支出编号
    cnt, cf, lc = COMPACT_CNT['关联单号'], LINK_CNT_FIX, PI['下拉标签']
    _blk_counter(ws, cnt, N_APV, lambda bs, r: f'{H_PI}!${lc}${bs}:${lc}{r}', '"?*"')
    for i in range(N_FIX):
        r = i + 2
        prev = f'+{cf}{r - 1}' if i else ''
        ws[f'{cf}{r}'] = f'=IF(AND(INDEX(固_有效,{i + 1})=1,INDEX(固_编号,{i + 1})<>""),1,0){prev}'
    na, nf = f'${cnt}${N_APV + 1}', f'${cf}${N_FIX + 1}'
    out = LINK_DV
    for i in range(LINK_N):
        r = i + 2
        k = i + 1
        fx = f'MATCH({k}-{na},${cf}$2:${cf}${N_FIX + 1},0)'
        ws[f'{out}{r}'] = (f'=IF({k}>${out}$1,"",IF({k}<={na},INDEX(批_下拉标签,MATCH({k},${cnt}$2:${cnt}${N_APV + 1},0)),'
                           f'INDEX(固_编号,{fx})&" "&IF(INDEX(固_项目,{fx})="",INDEX(固_类别,{fx}),INDEX(固_项目,{fx}))))')
    ws[f'{out}1'] = f'=MIN({LINK_N},{na}+{nf})'
    for c in list(COMPACT_CNT.values()) + [cf]:
        ws[f'{c}1'] = '计数'
    for k, c in UNIT_DV.items():
        ws[f'{c}1'].font = F_HELP


