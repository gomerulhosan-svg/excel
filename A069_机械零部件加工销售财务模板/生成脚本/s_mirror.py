def _hdr(ws, cols):
    for c, f, _d in cols:
        ws[f'{c}1'] = f
        ws[f'{c}1'].font = F_HELP


def chain(pairs, default='""'):
    out = default
    for c, v in reversed(pairs):
        out = f'IF({c},{v},{out})'
    return out


def _ix(sh, col, n_ref, block=None):
    return f'INDEX({inref(sh, col, block=block)},{n_ref}+1)'


def vdate(x):
    """真日期（2000～2099 年）取整，不然 0"""
    return f'IF(ISNUMBER({x}),IF(AND({x}>=36526,{x}<73051),INT({x}),0),0)'


def txt(x):
    return f'TRIM({x}&"")'


def raw(x):
    return f'TRIM({x}&"")<>""'


def numv(x):
    return f'IF(ISNUMBER({x}),{x},0)'


def badnum(x):
    return f'AND({raw(x)},NOT(ISNUMBER({x})))'


def unit_no(nm):
    """规范后的名字 → 往来单位第几家（简称、全称、别名都认；0＝不在表里）"""
    e = esc(nm)
    return (f'IF({nm}="",0,IFERROR(MATCH({e},位_简称,0),IFERROR(MATCH({e},位_全称规,0),'
            f'IFERROR(MATCH("*、"&{e}&"、*",位_别名规,0),0))))')


def month_any(x):
    """月份格：真日期 → 年月；202610 这样的数 → 本身；看不懂 → 0"""
    return (f'IF(ISNUMBER({x}),IF(AND({x}>=200001,{x}<=209912,INT({x})={x},MOD({x},100)>=1,MOD({x},100)<=12),{x},'
            f'IF(AND({x}>=36526,{x}<73051),YEAR({x})*100+MONTH({x}),0)),0)')


def month_own(x, d):
    """所属月份：填 1～12 ＝ 付款日往前最近的那个月；日期、202609 也认；看不懂 → 0"""
    return (f'IF(ISNUMBER({x}),IF(AND({x}>=1,{x}<=12,INT({x})={x}),IF({x}<=MONTH({d}),YEAR({d})*100+{x},(YEAR({d})-1)*100+{x}),'
            f'{month_any(x)}),0)')


def in_list(items, x):
    return 'OR(' + ','.join(f'{x}="{k}"' for k in items) + ')'


TXT_DATE = '"✗ 日期是文字：有「.」的用查找替换换成「-」；复制来的选中日期列 → 数据 → 分列 → 完成"'

