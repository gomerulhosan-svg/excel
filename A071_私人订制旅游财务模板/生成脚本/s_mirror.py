def build_par(ws):
    P = lambda k: f'{SH_BASE}!$C${PAR_ROW[k]}'
    first = ('IF(COUNTIF(单_预订日期,">0")+COUNTIF(收_日期,">0")=0,0,'
             'MIN(IF(COUNTIF(单_预订日期,">0")=0,99999,SMALL(单_预订日期,COUNTIF(单_预订日期,0)+1)),'
             'IF(COUNTIF(收_日期,">0")=0,99999,SMALL(收_日期,COUNTIF(收_日期,0)+1))))')
    b = lambda k: PAR[k]
    mx = 'MAX(MAX(单_预订日期),MAX(单_定金日期),MAX(单_取消日期),MAX(单_结算日期),MAX(收_已付日期))'
    rows = {
        '公司名称': f'=TRIM({P("公司名称")}&"")',
        '建账日': f'=IF(ISNUMBER({P("建账日")}),INT({P("建账日")}),IF({first}>0,{first},DATE(2026,1,1)))',
        '最后日期': f'=IF({mx}>0,{mx},{b("建账日")})',
        '截止': f'=IF(ISNUMBER({SH_HOME}!${HOME_END[0]}${HOME_END[1:]}),INT({SH_HOME}!${HOME_END[0]}${HOME_END[1:]}),{b("最后日期")})',
        '年度': f'=YEAR({b("截止")})',
        '年初': f'=DATE({b("年度")},1,1)',
        '默认账户': f'=IF({H_TAB}!${COMPACT["账户"][0]}$2="","现金",{H_TAB}!${COMPACT["账户"][0]}$2)',
        '截止年月': f'=YEAR({b("截止")})*100+MONTH({b("截止")})',
        '月初': f'=DATE(YEAR({b("截止")}),MONTH({b("截止")}),1)',
        '下一单号': f'=IF(MAX(单_号数值)>0,MAX(单_号数值)+1,MOD(YEAR({b("截止")}),100)*1000+1)',
        '尾款天数': f'=IF(N({P("尾款天数")})>0,N({P("尾款天数")}),15)',
        '结算天数': f'=IF(N({P("结算天数")})>0,N({P("结算天数")}),30)',
        '第二晚': '=LARGE($C$2:$C$11,2)',
        '订单末行': f'=MAX(MAX(单_末行),{ORD_HDR + 1})+1',
        '收支末行': f'=MAX(MAX(收_末行),{CASH_HDR + 1})+1',
    }
    for i, nm in enumerate(('单_预订日期', '单_定金日期', '单_取消日期', '单_结算日期', '收_已付日期')):
        ws[f'C{2 + 2 * i}'] = f'=LARGE({nm},1)'
        ws[f'C{3 + 2 * i}'] = f'=LARGE({nm},2)'
    for i, (key, _t, _tr, hr, cap) in enumerate(BASE_BLOCKS):
        if i + 1 < len(BASE_BLOCKS):
            nxt = BASE_BLOCKS[i + 1][1]
            rows[f'{key}位'] = f'=IFERROR(MATCH("{nxt}",{SH_BASE}!$A:$A,0)-ROW({SH_BASE}!$A${hr})-1,{cap})'
        else:
            rows[f'{key}位'] = f'={cap + 300}'
    ws['A1'] = '全书共用的参数（自动，别改）'
    for k, cell in PAR.items():
        r = int(cell[1:])
        ws[f'A{r}'] = k
        ws[cell] = rows[k]


