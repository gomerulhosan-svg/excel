"""隐藏计算表：_参（全书参数）、_表（基础资料逐行镜像＋压紧的下拉清单）、_单（订单登记逐条）、_收（收支登记逐条）。
   全部按「第 n 条」取数：INDEX(录入表!$X$表头行:$X$1048576, n+1)，插行删行不错位。查看表只用 layout.NAMES 里的名称。"""
from layout import *
from common import F_HELP


def _hdr(ws, cols):
    for c, f, _d in cols:
        ws[f'{c}1'] = f
        ws[f'{c}1'].font = F_HELP


def chain(pairs, default='""'):
    out = default
    for c, v in reversed(pairs):
        out = f'IF({c},{v},{out})'
    return out


def _ix(sh, col, n_ref, block=None):
    return f'INDEX({inref(sh, col, block=block)},{n_ref}+1)'


def vdate(x):
    """真日期（2000～2099 年）取整，不然 0"""
    return f'IF(ISNUMBER({x}),IF(AND({x}>=36526,{x}<73051),INT({x}),0),0)'


def txt(x):
    return f'TRIM({x}&"")'


def in_list(name_rng, x):
    return f'COUNTIF({name_rng},{esc(x)})>0'


