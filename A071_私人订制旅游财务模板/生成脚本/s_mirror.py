def build_dan(ws):
    _hdr(ws, DAN_COLS)
    D, C = DAN, ORD_COLS
    for i in range(N_ORD):
        r, n = i + 2, i + 1
        ws[f'A{r}'] = n
        x = lambda k: _ix(SH_ORD, C[k], f'$A{r}')
        c = lambda k: f'{D[k]}{r}'
        # 原始取数（不准引用 P_截止）
        ws[c('订单号')] = f'={txt(x("订单号"))}'
        ws[c('键')] = f'=IF({c("订单号")}="","","#"&{c("订单号")})'
        ws[c('预订日期')] = f'={vdate(x("预订日期"))}'
        ws[c('出行日期')] = f'={vdate(x("出行日期"))}'
        for k in ('客户名字', '销售', '联系电话', '线路', '备注'):
            ws[c(k)] = f'={txt(x(k))}'
        for k in ('订单总金额', '预计成本', '人数'):
            ws[c(k)] = f'=N({x(k)})'
        ws[c('有预计')] = f'=IF(ISNUMBER({x("预计成本")}),1,0)'
        ws[c('定金')] = f'=N({x("定金金额")})'
        ws[c('定金日期')] = f'=IF({c("定金")}=0,0,IF({vdate(x("定金日期"))}>0,{vdate(x("定金日期"))},{c("预订日期")}))'
        ws[c('收款账户')] = f'=IF({txt(x("收款账户"))}="",P_默认账户,{txt(x("收款账户"))})'
        ws[c('取消日期')] = f'={vdate(x("取消日期"))}'
        ws[c('取消填了')] = f'=IF({txt(x("取消日期"))}<>"",1,0)'
        ws[c('结算日期')] = f'={vdate(x("结算日期"))}'
        own = x('提成比例')
        per = f'IF({c("销售")}="",0,IFERROR(INDEX(人员_提成比例,MATCH({esc(c("销售"))},人员_姓名,0)),0))'
        ws[c('提成比例')] = f'=IF(ISNUMBER({own}),IF({own}>=1,{own}/100,{own}),{per})'
        ws[c('有效')] = (f'=IF(AND({c("订单号")}<>"",OR({c("客户名字")}<>"",{c("订单总金额")}<>0,{c("预订日期")}>0,'
                       f'{c("定金")}<>0)),1,0)')
        # 往下可以引用截止日
        v1 = f'{c("有效")}<>1'
        key = esc(c('键'))
        ws[c('定金计入')] = f'=IF(AND({c("定金日期")}>0,{c("定金日期")}<=P_截止),{c("定金")},0)'
        upto = '收_日期,"<="&P_截止'
        ws[c('订单净收')] = (f'=IF({v1},0,SUMIFS(收_已付额,收_订单键,{key},收_归类,"订单收款",{upto})'
                          f'+SUMIFS(收_已付额,收_订单键,{key},收_归类,"订单退款",{upto}))')
        ws[c('已收')] = f'=ROUND({c("定金计入")}+{c("订单净收")},2)'
        ws[c('取消')] = f'=IF({c("取消填了")}=1,IF({c("取消日期")}=0,1,IF({c("取消日期")}<=P_截止,1,0)),0)'
        ws[c('退款未付')] = f'=IF({v1},0,SUMIFS(收_未付额,收_订单键,{key},收_归类,"订单退款"))'
        ws[c('有效金额')] = f'=IF({c("取消")}=1,ROUND({c("已收")}-{c("退款未付")},2),{c("订单总金额")})'
        ws[c('还没收')] = f'=IF({c("取消")}=1,0,ROUND({c("订单总金额")}-{c("已收")},2))'
        ac = c('还没收')
        ws[c('尾款收否')] = (f'=IF({v1},"",IF({c("取消")}=1,"已取消",IF({ac}<-0.005,"多收 "&TEXT(-{ac},"#,##0.00"),'
                          f'IF({ac}<=0.005,"已收齐",IF({c("订单净收")}>0.005,"部分","未收")))))')
        ws[c('实际成本')] = f'=IF({v1},0,ROUND(SUMIFS(收_支出净额,收_订单键,{key},收_归类,"订单成本"),2))'
        ws[c('未付成本')] = f'=IF({v1},0,ROUND(SUMIFS(收_未付额,收_订单键,{key},收_归类,"订单成本"),2))'
        ws[c('实际利润')] = f'=ROUND({c("有效金额")}-{c("实际成本")},2)'
        ws[c('预计利润')] = f'=IF({c("取消")}=1,{c("实际利润")},IF({c("有预计")}=1,ROUND({c("订单总金额")}-{c("预计成本")},2),0))'
        ws[c('结算')] = f'=IF(AND({c("结算日期")}>0,{c("结算日期")}<=P_截止),1,0)'
        ws[c('出行码')] = (f'=IF({v1},0,IF({c("取消")}=1,3,IF({c("结算")}=1,2,'
                        f'IF(AND({c("出行日期")}>0,{c("出行日期")}<=P_截止),1,0))))')
        ws[c('出行状态')] = f'=IF({v1},"",CHOOSE({c("出行码")}+1,"未出行","已出行","已结算","已取消"))'
        ws[c('本单利润')] = f'=IF(OR({c("结算")}=1,{c("取消")}=1),{c("实际利润")},{c("预计利润")})'
        ws[c('提成基数')] = (f'=IF({c("销售")}="","利润",IFERROR(IF(INDEX(人员_提成基数,MATCH({esc(c("销售"))},人员_姓名,0))'
                          f'="订单金额","订单金额","利润"),"利润"))')
        ws[c('订单提成')] = (f'=IF(OR({v1},{c("取消")}=1),0,ROUND(MAX(0,{c("提成比例")}*'
                          f'IF({c("提成基数")}="订单金额",{c("订单总金额")},{c("本单利润")})),2))')
        ws[c('应发')] = f'=IF(AND({c("有效")}=1,{c("结算")}=1,{c("取消")}=0),1,0)'
        for k, d in (('预订年月', '预订日期'), ('出行年月', '出行日期'), ('定金年月', '定金日期'), ('结算年月', '结算日期'),
                     ('取消年月', '取消日期')):
            ws[c(k)] = f'={ym(c(d))}'
        has = (f'OR({c("订单号")}<>"",{c("客户名字")}<>"",{c("订单总金额")}<>0,{c("定金")}<>0,{c("预订日期")}>0)')
        raw = lambda k: f'TRIM({x(k)}&"")<>""'
        ox = x('订单号')
        dup_dep = (f'COUNTIFS(收_订单键,{key},收_归类,"订单收款",收_收入,{c("定金")},收_日期,">="&({c("定金日期")}-7),'
                   f'收_日期,"<="&({c("定金日期")}+7))>0')
        ws[c('校验')] = '=' + chain([
            (f'NOT({has})', '""'),
            (f'{c("订单号")}=""', '"✗ 没填订单号（这一行不算）"'),
            (f'COUNTIF(单_键,{key})>1', '"✗ 订单号重复了"'),
            (f'{c("预订日期")}=0', 'IF(' + raw('预订日期') + ',"✗ 预订日期不对（要像 2026/9/1 这样）","✗ 没填预订日期")'),
            (f'AND({c("订单总金额")}<=0,{c("取消")}=0)', '"✗ 没填订单总金额"'),
            (f'AND({raw("出行日期")},{c("出行日期")}=0)', '"✗ 出行日期不对（要像 2026/9/1 这样）"'),
            (f'AND({c("取消填了")}=1,{c("取消日期")}=0)', '"✗ 取消日期不对（先按已取消算）"'),
            (f'AND({raw("结算日期")},{c("结算日期")}=0)', '"✗ 结算日期不对（要像 2026/9/1 这样）"'),
            (f'AND({c("定金")}<>0,NOT({in_list("账户_名称", c("收款账户"))}))', '"✗ 定金收款账户不在基础资料里"'),
            (f'AND(ISNUMBER({ox}),{ox}>=36526,{ox}<=73050)', '"⚠ 订单号像是被改成了日期：把这格设成文本格式再重输"'),
            (f'AND({raw("定金日期")},{vdate(x("定金日期"))}=0)', '"⚠ 定金收款日期不对，先按预订日期算"'),
            (f'AND({c("定金")}<>0,{c("定金日期")}>P_截止)', '"⚠ 定金日期晚于截止日期，暂不算收到"'),
            (f'AND({c("取消")}=0,{c("出行日期")}=0)', '"⚠ 没填出行日期（先算未出行）"'),
            (f'AND({c("出行日期")}>0,{c("出行日期")}<{c("预订日期")})', '"⚠ 出行日期比预订日期还早"'),
            (f'{c("销售")}=""', '"⚠ 没填销售名字（没有提成）"'),
            (f'AND(NOT({in_list("人员_姓名", c("销售"))}),NOT(ISNUMBER({own})))', '"⚠ 销售名字不在基础资料的人员里（提成按 0 算）"'),
            (f'AND({c("出行码")}<=1,{c("有预计")}=0)', '"⚠ 没填预计成本（预计利润没算进去）"'),
            (f'{ac}<-0.005', '"⚠ 多收了 "&TEXT(-' + ac + ',"#,##0.00")&"：客户加了项目请改订单总金额；或者定金在收支登记又记了一遍"'),
            (f'AND({c("定金")}>0,{dup_dep})', '"⚠ 收支登记里有一笔跟定金一样多的收款，是不是定金记重了"'),
            (f'AND({c("取消")}=0,{ac}>0.005,COUNTIFS(收_订单键,{key},收_归类,"订单退款",收_未付,0)>0)',
             '"⚠ 有退款：部分退团或减项的，请把订单总金额改小"'),
            (f'AND({c("取消填了")}=1,{c("结算日期")}>0)', '"⚠ 取消日期和结算日期都填了（按已取消算）"'),
            (f'AND({c("结算")}=1,{ac}>0.005)', '"⚠ 还没收齐就结算了（还差 "&TEXT(' + ac + ',"#,##0.00")&"）"'),
            (f'AND({c("结算")}=1,OR({c("实际成本")}=0,AND({c("有预计")}=1,{c("实际成本")}<{c("预计成本")}*0.5)))',
             '"⚠ 结算了，成本可能没记全（实际成本是 0 或不到预计成本的一半）"'),
            (f'AND({c("结算日期")}>0,{c("出行日期")}>0,{c("结算日期")}<{c("出行日期")})', '"⚠ 结算日期比出行日期还早"'),
            (f'AND({c("出行码")}=1,{c("实际成本")}=0)', '"⚠ 已出行，还没记成本"'),
            (f'AND({c("出行码")}=1,P_截止-{c("出行日期")}>P_结算天数)', '"⚠ 出行超过 "&P_结算天数&" 天还没结算"'),
            (f'AND({c("出行码")}<=1,{c("有预计")}=1,{c("实际成本")}>{c("预计成本")}+0.005)', '"⚠ 已记的成本超过了预计成本，请核对预计成本"'),
            (f'ABS(YEAR({c("预订日期")})-YEAR(P_截止))>2', '"⚠ 预订日期的年份对吗？"'),
            (f'AND({c("结算日期")}>0,COUNTIFS(收_订单键,{key},收_归类,"订单成本",收_日期,">"&{c("结算日期")})>0)',
             '"ℹ 结算以后又记了这单的成本（原来欠着、后来付了的不用管；新加的成本会改掉实际利润和提成）"'),
        ])
        ws[c('录入行')] = f'=ROW({SH_ORD}!$A${ORD_HDR})+$A{r}'
        ws[c('标签')] = (f'=IF({v1},"",{c("订单号")}&"｜"&{c("客户名字")}&IF({c("出行日期")}>0,"｜出行 "&TEXT({c("出行日期")},"m/d"),""))')
        b = c('订单号')
        pure = ','.join(f'ISERROR(FIND("{ch}",UPPER({b})))' for ch in '-/.:E ')
        ws[c('号数值')] = f'=IF(AND({b}<>"",{pure}),IFERROR(IF(AND(--{b}>0,--{b}<1E+9),--{b},0),0),0)'
        ws[c('预订键')] = f'=IF(AND({c("有效")}=1,{c("预订日期")}>0),{c("预订日期")}*10000+$A{r},"")'
        ws[c('出行键')] = f'=IF({c("有效")}=1,IF({c("出行日期")}>0,{c("出行日期")},99999)*10000+$A{r},"")'
        ws[c('实际显示')] = f'=IF({v1},"",IF({c("出行码")}>=1,{c("实际利润")},""))'
        ws[c('开放')] = f'=IF(AND({c("有效")}=1,{c("结算")}=0,OR({c("取消")}=0,P_截止-{c("取消日期")}<=60)),1,0)'
        ws[c('出行天数')] = f'=IF(AND({c("有效")}=1,{c("出行日期")}>0,{c("出行日期")}<=P_截止),P_截止-{c("出行日期")},"")'
        ws[c('末行')] = f'=IF({has},{c("录入行")},0)'


# ───────────────────────── _收 ─────────────────────────
def build_shou(ws):
    _hdr(ws, SHOU_COLS)
    S, C = SHOU, CASH_COLS
    for i in range(N_CASH):
        r, n = i + 2, i + 1
        ws[f'A{r}'] = n
        x = lambda k: _ix(SH_CASH, C[k], f'$A{r}')
        c = lambda k: f'{S[k]}{r}'
        # 原始取数（不准引用 P_截止、P_建账日）
        ws[c('日期')] = f'={vdate(x("日期"))}'
        for k in ('类别', '往来对象', '摘要', '备注'):
            ws[c(k)] = f'={txt(x(k))}'
        o = txt(x('订单号'))
        ws[c('订单号')] = f'=IFERROR(TRIM(LEFT({o},FIND("｜",{o})-1)),{o})'
        ws[c('订单键')] = f'=IF({c("订单号")}="","","#"&{c("订单号")})'
        ws[c('收入')] = f'=N({x("收入")})'
        ws[c('支出')] = f'=N({x("支出")})'
        ws[c('账户')] = f'=IF({txt(x("账户"))}="",P_默认账户,{txt(x("账户"))})'
        ws[c('未付')] = f'=IF({txt(x("付款情况"))}="未付",1,0)'
        ws[c('有效')] = f'=IF(AND({c("日期")}>0,OR({c("收入")}<>0,{c("支出")}<>0)),1,0)'
        ws[c('归类')] = f'=IF({c("类别")}="","",IFERROR(INDEX(类别_归类,MATCH({esc(c("类别"))},类别_名称,0)),""))'
        ws[c('订单行')] = f'=IF({c("订单键")}="",0,IFERROR(MATCH({esc(c("订单键"))},单_键,0),0))'
        ws[c('订单找到')] = f'=IF({c("订单行")}>0,1,0)'
        ws[c('已付日期')] = f'=IF(AND({c("有效")}=1,{c("未付")}=0),{c("日期")},0)'
        # 往下可以引用截止日、建账日
        inc, out = f'{c("收入")}-{c("支出")}', f'{c("支出")}-{c("收入")}'
        ok = f'{c("有效")}=1'
        kind = lambda k: f'{c("归类")}="{k}"'
        ws[c('在期')] = (f'=IF(AND({ok},{c("未付")}=0,{c("日期")}>=P_建账日,{c("日期")}<=P_截止),1,0)')
        ws[c('净额')] = f'=IF({c("在期")}=1,{inc},0)'
        ws[c('已付额')] = f'=IF(AND({ok},{c("未付")}=0),{inc},0)'
        ws[c('未付额')] = f'=IF(AND({ok},{c("未付")}=1),MAX(0,{out}),0)'
        ws[c('支出净额')] = f'=IF({ok},{out},0)'
        ws[c('年月')] = f'={ym(c("日期"))}'
        has = f'OR({c("类别")}<>"",{c("收入")}<>0,{c("支出")}<>0,{c("日期")}>0,{c("订单号")}<>"")'
        raw = lambda k: f'TRIM({x(k)}&"")<>""'
        kinds = lambda ks: 'OR(' + ','.join(kind(k) for k in ks) + ')'
        dirn = f'IFERROR(INDEX(类别_方向,MATCH({esc(c("类别"))},类别_名称,0)),"")'
        orow = c('订单行')
        ws[c('校验')] = '=' + chain([
            (f'NOT({has})', '""'),
            (f'{c("日期")}=0', 'IF(' + raw('日期') + ',"✗ 日期不对（要像 2026/9/1 这样）","✗ 没填日期")'),
            (f'AND({c("收入")}=0,{c("支出")}=0)', '"✗ 没填金额"'),
            (f'{c("类别")}=""', '"✗ 没选收支类别"'),
            (f'{c("归类")}=""', '"✗ 收支类别不在基础资料里（或者没设归类）"'),
            (f'AND({kinds(ORDER_KINDS)},{c("订单号")}="")', '"✗ 这一类要选订单号"'),
            (f'AND({c("订单号")}<>"",{c("订单找到")}=0)', '"✗ 订单号在订单登记里找不到"'),
            (f'NOT({in_list("账户_名称", c("账户"))})', '"✗ 账户不在基础资料里"'),
            (f'AND({c("未付")}=1,{c("收入")}>0)', '"✗ 收入不能选「未付」：还没收到的钱先别记，到账再记"'),
            (f'AND({kinds(PERSON_KINDS)},NOT({in_list("人员_姓名", c("往来对象"))}))', '"✗ 工资、提成的往来对象要选人员表里的人"'),
            (f'AND({c("收入")}<>0,{c("支出")}<>0)', '"⚠ 收入、支出都填了（按收入－支出算）"'),
            (f'AND({c("未付")}=1,{kinds(["订单收款", "内部转账", "资金往来"])})', '"⚠ 「未付」只用在欠人家钱的支出上"'),
            (f'AND({dirn}="收入",{c("收入")}=0,{c("支出")}>0)', '"⚠ 这是收入类，金额填在了支出栏（会算成负数）"'),
            (f'AND({dirn}="支出",{c("支出")}=0,{c("收入")}>0,{c("归类")}<>"订单成本")', '"⚠ 这是支出类，金额填在了收入栏（会算成负数）"'),
            (f'AND({c("订单号")}<>"",NOT({kinds(ORDER_KINDS)}))', '"⚠ 这一类不算订单的，订单号不起作用"'),
            (f'{c("日期")}<P_建账日', '"⚠ 日期早于建账日期（资金余额不算这一笔，订单照算）"'),
            (f'{c("日期")}>P_截止', '"⚠ 日期晚于截止日期，暂不计入"'),
            (f'AND({c("未付")}=1,{kind("订单成本")},{orow}>0,N(INDEX(单_出行天数,{orow}))>P_结算天数)',
             '"⚠ 出行超过 "&P_结算天数&" 天还没付（欠供应商）"'),
            (f'ABS(YEAR({c("日期")})-YEAR(P_截止))>2', '"⚠ 日期的年份对吗？"'),
            (f'AND({kind("订单成本")},{orow}>0,INDEX(单_结算日期,{orow})>0,{c("日期")}>INDEX(单_结算日期,{orow}))',
             '"ℹ 这单已经结算了（原来欠着、后来付了的不用管；新加的成本会改掉实际利润和提成）"'),
        ])
        ws[c('录入行')] = f'=ROW({SH_CASH}!$A${CASH_HDR})+$A{r}'
        ws[c('显示摘要')] = f'=IF({c("摘要")}="",{c("类别")},{c("摘要")})'
        ws[c('订单客户')] = (f'=IF({orow}>0,INDEX(单_客户名字,{orow})&" · "&IF(INDEX(单_出行日期,{orow})>0,'
                          f'"出行 "&TEXT(INDEX(单_出行日期,{orow}),"m/d"),"没填出行日期")&" · 还没收 "&TEXT(INDEX(单_还没收,{orow}),"#,##0"),'
                          f'IF({c("订单号")}="","","找不到这个订单"))')
        ws[c('排序键')] = f'=IF({ok},{c("日期")}*10000+$A{r},"")'
        ws[c('末行')] = f'=IF({has},{c("录入行")},0)'

BUILDERS = {H_PAR: build_par, H_TAB: build_list, H_DAN: build_dan, H_SHOU: build_shou}


def build(wb, ctx=None):
    for name, fn in BUILDERS.items():
        fn(wb[name])
