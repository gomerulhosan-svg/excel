def build_list(ws):
    ws['A1'] = '账户'
    ws['D1'] = '收支类别'
    ws['H1'] = '人员'
    for i in range(LIST_N):
        r, n = i + 2, i + 1
        if n <= N_ACC:
            g = lambda k: _ix(SH_BASE, ACC_COLS[k], n, '账户')
            a = f'{LIST_ACC["名称"]}{r}'
            ws[a] = f'=IF({n}>P_账户位,"",TRIM({g("名称")}&""))'
            ws[f'{LIST_ACC["期初余额"]}{r}'] = f'=IF({a}="",0,N({g("期初余额")}))'
        if n <= N_CAT:
            g = lambda k: _ix(SH_BASE, CAT_COLS[k], n, '类别')
            a = f'{LIST_CAT["名称"]}{r}'
            ws[a] = f'=IF({n}>P_类别位,"",TRIM({g("名称")}&""))'
            ws[f'{LIST_CAT["方向"]}{r}'] = f'=IF({a}="","",IF(TRIM({g("方向")}&"")="","双向",TRIM({g("方向")}&"")))'
            ws[f'{LIST_CAT["归类"]}{r}'] = f'=IF({a}="","",TRIM({g("归类")}&""))'
        if n <= N_PER:
            g = lambda k: _ix(SH_BASE, PER_COLS[k], n, '人员')
            a = f'{LIST_PER["姓名"]}{r}'
            ws[a] = f'=IF({n}>P_人员位,"",TRIM({g("姓名")}&""))'
            ws[f'{LIST_PER["岗位"]}{r}'] = f'=IF({a}="","",TRIM({g("岗位")}&""))'
            ws[f'{LIST_PER["提成基数"]}{r}'] = f'=IF({a}="","",IF(TRIM({g("提成基数")}&"")="订单金额","订单金额","利润"))'
            ws[f'{LIST_PER["提成比例"]}{r}'] = f'=IF({a}="",0,IF(N({g("提成比例")})>=1,N({g("提成比例")})/100,N({g("提成比例")})))'
    # 压紧的清单（下拉用）：计数列逐行累加，清单第 k 个＝计数第一次到 k 的那行
    for key, (out, src, cap) in COMPACT.items():
        cnt = COMPACT_CNT[key]
        for i in range(cap):
            r = i + 2
            prev = f'+{cnt}{r - 1}' if i else ''
            ws[f'{cnt}{r}'] = f'=IF({src}{r}<>"",1,0){prev}'
            ws[f'{out}{r}'] = (f'=IF({i + 1}>${out}$1,"",INDEX(${src}$2:${src}${cap + 1},'
                               f'MATCH({i + 1},${cnt}$2:${cnt}${cap + 1},0)))')
        ws[f'{out}1'] = f'={cnt}{cap + 1}'
    # 订单下拉：只列开放的（没结算，没取消或取消不到 60 天），新的在上面（第 k 个＝倒数第 k 个）
    cnt, out, src = COMPACT_CNT['订单'], ORDER_DV, f'{H_DAN}!${DAN["标签"]}$'
    for i in range(N_ORD):
        r = i + 2
        bs = 2 + (i // 50) * 50                      # 50 条一段：链只有 60 层深（WPS 改一格不用整列重算）
        base = f'{cnt}{bs - 1}+' if bs > 2 else ''
        ws[f'{cnt}{r}'] = f'={base}COUNTIF({H_DAN}!${DAN["开放"]}${bs}:{DAN["开放"]}{r},1)'
        ws[f'{out}{r}'] = (f'=IF({i + 1}>${out}$1,"",INDEX({src}2:{src}{N_ORD + 1},'
                           f'MATCH(${out}$1-{i},${cnt}$2:${cnt}${N_ORD + 1},0)))')
    ws[f'{out}1'] = f'={cnt}{N_ORD + 1}'
    for c in list(COMPACT_CNT.values()):
        ws[f'{c}1'] = '计数'


