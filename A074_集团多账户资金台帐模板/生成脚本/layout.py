def _alloc(start, specs, gap=1):
    """按顺序给 _表 分列：specs＝[(组名, [字段…])]，组之间空 gap 列 → {组名: {字段: 列}}"""
    i, out = CI(start), {}
    for grp, fields in specs:
        out[grp] = {}
        for f in fields:
            out[grp][f] = CL(i)
            i += 1
        i += gap
    return out, CL(i)


