def win_first(ym):
    """可能有「月码 ≥ ym」的第一行（_流 第几条）"""
    return f'MIN({N_LEDGER},COUNTIF(块_至最晚月,"<"&({ym}))*{BLK}+1)'


def win_last(ym, first='1'):
    """可能有「月码 ≤ ym」的最后一行；不小于 first"""
    return f'MAX({first},COUNTIF(块_后最早月,"<="&({ym}))*{BLK})'


def win_before(ym):
    """可能有「月码 < ym」的最后一行（年初余额、期初用：区间 [1, 它]）"""
    return f'MAX(1,COUNTIF(块_后最早月,"<"&({ym}))*{BLK})'


def win(name, first, last):
    """名称在窗口 [first,last] 的一段：INDEX(流_x,first):INDEX(流_x,last)。first/last 放报表的 EFF 帮助格"""
    return f'INDEX({name},{first}):INDEX({name},{last})'


def k_aypm(no, y, p, m):
    """((号×10^4＋年)×10＋属性)×100＋月：账年属月键 / 归年属月键 / 项年属月键 / 人年属月键"""
    return f'((({no})*{K_Y}+({y}))*{K_P}+({p}))*{K_M}+({m})'


def k_igypm(i, g, y, p, m):
    """项归年属月键：((((项号×100＋归属号)×10^4＋年)×10＋属性)×100＋月"""
    return k_aypm(f'({i})*{K_G}+({g})', y, p, m)


def k_year_lo(no, y):
    """号在年份 y 的第一个键（含所有属性、月）"""
    return f'(({no})*{K_Y}+({y}))*{K_P * K_M}'


def k_year_hi(no, y):
    """号在年份 y 的最后一个键＋1（用 "<"）"""
    return f'(({no})*{K_Y}+({y})+1)*{K_P * K_M}'


def sum_year(val, keyname, no, y, p=None, m1=1, m2=12, p2=None):
    """号在 y 年的合计：p=None 所有属性整年；p 给了＝属性 p（m1..m2 月）；p2 给了＝属性 p..p2 整年（如 1..ATTR_NOINT_HI 不含内部）"""
    if p is None:
        return f'SUMIFS({val},{keyname},">="&{k_year_lo(no, y)},{keyname},"<"&{k_year_hi(no, y)})'
    if p2 is not None:
        return f'SUMIFS({val},{keyname},">="&{k_aypm(no, y, p, 1)},{keyname},"<="&{k_aypm(no, y, p2, 12)})'
    return f'SUMIFS({val},{keyname},">="&{k_aypm(no, y, p, m1)},{keyname},"<="&{k_aypm(no, y, p, m2)})'


def sum_before_year(val, keyname, no, y):
    """号在 y 年以前（所有属性）的合计：年初余额用"""
    return f'SUMIFS({val},{keyname},">="&(({no})*{K_Y})*{K_P * K_M},{keyname},"<"&{k_year_lo(no, y)})'


def next_pos(prev, key, keyname, n_last):
    """链式找下一条：从 prev（上一条在 _流 的位置，0＝从头）往后找第一个 键＝key 的位置；没有＝0。
       keyname＝_流 的键列名称（如 流_账年键）；n_last＝该名称的行数（N_LEDGER）"""
    return (f'IFERROR(IF({prev}>={n_last},0,{prev}+MATCH({key},INDEX({keyname},{prev}+1):INDEX({keyname},{n_last}),0)),0)')


def last_day(a, d):
    """账户 a 在日期 d（含）以前最后一笔的日期；没有＝0（首页「最后一笔」、几天没记）"""
    k = f'IFERROR(LARGE(流_账日键,COUNTIF(流_账日键,">"&(({a})*{K_DAY}+({d})))+1),0)'
    return f'IF({k}>=({a})*{K_DAY},{k}-({a})*{K_DAY},0)'


