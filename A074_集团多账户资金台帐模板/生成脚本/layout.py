def q(sh):
    """公式里引用表名：含 - （ ） 空格等的要加单引号"""
    return sh if re.fullmatch(r'[_A-Za-z一-鿿][\w一-鿿]*', sh) else "'" + sh.replace("'", "''") + "'"


def inref(sh, col, last=None, block=None, hdr=None):
    """录入表 / 基础资料某列的锚定区域（从表头行开始），配合 INDEX(区域, n+1) 用。
       基础资料默认封顶到 BASE_LAST[block]（块里插行会跟着撑大；不再盖到别的块，见 设计 §2.2）"""
    if hdr is None:
        hdr = BASE_HDR[block] if sh == SH_BASE else HDR
    if last is None:
        last = BASE_LAST[block] if sh == SH_BASE else REF_END
    return f"{q(sh)}!${col}${hdr}:${col}${last}"


def lref(field, n):
    """资金台帐第 n 条（n 是公式片段）的某个录入格：INDEX(资金台帐!$X$4:$X$1048576,n+1)"""
    return f'INDEX({inref(SH_LEDGER, LEDGER_COLS[field])},{n}+1)'


def lrange(field):
    """资金台帐某列第 1..N_LEDGER 条（锚在表头，插删行不漏）：给核对表比对、计数用"""
    r = inref(SH_LEDGER, {**LEDGER_COLS, **LEDGER_SHOW}[field])
    return f'INDEX({r},2):INDEX({r},{N_LEDGER + 1})'


def esc(x):
    """当 SUMIFS/COUNTIFS/MATCH/SEARCH 的条件用时，把 ~ * ? 转义成普通字符"""
    return f'SUBSTITUTE(SUBSTITUTE(SUBSTITUTE({x},"~","~~"),"*","~*"),"?","~?")'


def norm(x):
    """名字规范写法：去半角/全角/不换行空格、换行，半角括号改全角"""
    return (f'SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(TRIM({x}&"")," ",""),"　","")," ",""),'
            f'CHAR(10),""),"(","（"),")","）")')


def raw(x):
    """格子里有东西（空格不算）"""
    return f'TRIM({x}&"")<>""'


def name2no(x, pre):
    """名字 → 号（pre＝'账户'/'公司'/'项'/'人'）：空＝0；先比 名称规，再比 别名规（"*、名字、*"）；认不出＝0。
       _表 里空槽的名称规是 CHAR(1)、空别名的别名规是 ""，所以空名字、空槽永远对不上（设计 §2.2）"""
    n = esc(norm(x))
    alias = (f',IFERROR(MATCH("*、"&{n}&"、*",{pre}_别名规,0),0)' if pre != '公司' else ',0')
    return f'IF(TRIM({x}&"")="",0,IFERROR(MATCH({n},{pre}_名称规,0){alias}))'


def _ymd8(v):
    """8 位数 v（20261001）→ 日期；不是合法的年月日＝0"""
    return (f'IF(AND({v}>=20000101,{v}<=20991231,INT({v})={v},MOD(INT({v}/100),100)>=1,MOD(INT({v}/100),100)<=12,MOD({v},100)>=1,'
            f'MOD({v},100)<=DAY(EOMONTH(DATE(INT({v}/10000),MOD(INT({v}/100),100),1),0))),'
            f'DATE(INT({v}/10000),MOD(INT({v}/100),100),MOD({v},100)),0)')


def vdate(x):
    """真日期取整（2000～2099）；8 位数 20261001（数字或文字）；文字（开头四位是 2000～2099 的年，「-」「/」「.」「年月日」分隔，可带时间）也认；认不出＝0。
    文字开头四位必须是年份：Excel 会把「10-1」「10.1」这种文字自己转成当年日期，不能让它混过去。"""
    t = f'LEFT(TRIM({x}),10)'
    s = (f'SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE({t},".","-"),"/","-"),"年","-"),"月","-"),"日","")')
    y4 = f'IFERROR(AND(--LEFT(TRIM({x}),4)>=2000,--LEFT(TRIM({x}),4)<=2099),FALSE)'
    d8 = f'IFERROR(IF(AND(LEN(TRIM({x}))=8,ISNUMBER(--TRIM({x}))),{_ymd8(f"(--TRIM({x}))")},0),0)'
    return (f'IF(ISNUMBER({x}),IF(AND({x}>=36526,{x}<73051),INT({x}),{_ymd8(x)}),'
            f'IF(ISTEXT({x}),IF({d8}>0,{d8},IF({y4},IFERROR(IF(AND(--({s})>=36526,--({s})<73051),INT(--({s})),0),0),0)),0))')


def vdate_text(x):
    """日期格是文字、而且认出来了（给 △「日期是文字，已照认」）"""
    return f'AND(ISTEXT({x}),{vdate(x)}>0)'


def numv(x):
    """金额：数字 ROUND 2；文字去掉 , ， ¥ ￥ 再转；空、「-」「--」「—」当 0；认不出＝0（问题列另报 ※）"""
    t = f'TRIM({x}&"")'
    s = f'SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE({t},",",""),"，",""),"¥",""),"￥","")'
    return (f'IF(ISNUMBER({x}),ROUND({x},2),IF(OR({t}="",{t}="-",{t}="--",{t}="—",{t}="－"),0,'
            f'IFERROR(ROUND(--{s},2),0)))')


def numv_bad(x):
    """金额格有字但认不出（「10000+200」这种）"""
    t = f'TRIM({x}&"")'
    s = f'SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE({t},",",""),"，",""),"¥",""),"￥","")'
    return (f'AND(ISTEXT({x}),NOT(OR({t}="",{t}="-",{t}="--",{t}="—",{t}="－")),NOT(ISNUMBER(IFERROR(--{s},""))))')


def money_in(xin, xout):
    """_流 收：MAX(收,0)+MAX(−支,0)（负数当另一栏）"""
    return f'ROUND(MAX({numv(xin)},0)+MAX(-({numv(xout)}),0),2)'


def money_out(xin, xout):
    return f'ROUND(MAX({numv(xout)},0)+MAX(-({numv(xin)}),0),2)'


def chain(pairs, default='""'):
    """[(条件, 值), …] → IF(条件1,值1,IF(条件2,值2,…,默认))"""
    out = default
    for c, v in reversed(pairs):
        out = f'IF({c},{v},{out})'
    return out


